// Rooms check in headless Chrome (needs `npm run dev` and the server: `cd ../server && cargo run -p dark-server -- --dev`).
// usage: node scripts/rooms-probe.mjs <outdir>
import puppeteer from 'puppeteer-core'
const OUT = process.argv[2]
const URL = 'http://localhost:5173/'
const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
const browser = await puppeteer.launch({ executablePath: CHROME, headless: 'new', protocolTimeout: 300_000, args: ['--use-angle=metal', '--ignore-gpu-blocklist', '--mute-audio'] })
const log = (...a) => console.log(...a.map((x) => typeof x === 'object' ? JSON.stringify(x) : x))
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
async function open(ctx, url, vp) {
  const p = await ctx.newPage()
  await p.setViewport(vp)
  p.on('pageerror', (e) => log('PAGEERR', String(e).slice(0, 200)))
  await p.goto(url, { waitUntil: 'domcontentloaded' })
  await p.waitForFunction(() => window.__game, { timeout: 120_000, polling: 250 })
  return p
}
const net = (p) => p.evaluate(() => { const n = window.__game.store.get().net; return { status: n.status, msg: n.message, code: n.room?.code, me: n.me, owner: n.owner, players: n.players.map((x) => x.name), max: n.room?.max_players, priv: n.room?.private } })
const desk = { width: 1280, height: 720 }
const ctxA = await browser.createBrowserContext()
const ctxB = await browser.createBrowserContext()
// A: the owner, on the island map
const a = await open(ctxA, URL + '?map=island&tier=low', desk)
await a.evaluate(() => window.__game.setPlayerName('Asha'))
await sleep(1500)
await a.screenshot({ path: `${OUT}/1-landing-empty.png` })
await a.click('[data-testid=room-settings]')
await sleep(400)
await a.screenshot({ path: `${OUT}/2-room-settings.png` })
await a.keyboard.press('Escape')
await a.evaluate(() => window.__game.setRoomSetup({ name: 'Asha island run', maxPlayers: 12, roadkill: true }))
await a.evaluate(() => window.__game.play())
await a.waitForFunction(() => window.__game.store.get().net.status === 'online', { timeout: 20_000 })
const A0 = await net(a); log('A after play', A0)
// B: a stranger on a random endless world sees the room and joins it (reloads onto the island)
const b = await open(ctxB, URL + '?tier=low', desk)
await b.evaluate(() => window.__game.setPlayerName('Ravi'))
await b.waitForSelector(`[data-testid=join-${A0.code}]`, { timeout: 10_000 })
await sleep(500)
await b.screenshot({ path: `${OUT}/3-landing-list.png` })
await b.click(`[data-testid=join-${A0.code}]`)
await b.waitForNavigation({ waitUntil: 'domcontentloaded', timeout: 30_000 })
log('B url', b.url())
await b.waitForFunction(() => window.__game && window.__game.store.get().net.status === 'online' && window.__game.store.get().net.players.length >= 2, { timeout: 60_000, polling: 250 })
log('B joined', await net(b), 'map', await b.evaluate(() => window.__game.map?.id))
await a.waitForFunction(() => window.__game.store.get().net.players.length >= 2, { timeout: 10_000 })
log('A sees', await net(a))
// wait for both worlds, then see each other
await a.waitForFunction(() => window.__game.store.get().worldReady, { timeout: 120_000, polling: 500 })
await b.waitForFunction(() => window.__game.store.get().worldReady, { timeout: 120_000, polling: 500 })
await sleep(4000)
log('A remotes', await a.evaluate(() => { const r = window.__game.remotes; return r.players ? r.players.size : JSON.stringify(Object.keys(r)) }))
log('pos A', await a.evaluate(() => window.__game.localPose && window.__game.localPose().pos), 'pos B', await b.evaluate(() => window.__game.localPose().pos))
await b.screenshot({ path: `${OUT}/4-b-ingame.png` })
// A turns to face B: the remote character + name tag
const bp = await b.evaluate(() => { const p = window.__game.localPose(); return { x: p.x, z: p.z } })
log('B pose', bp, 'A sees remote at', await a.evaluate(() => { const r = [...window.__game.remotes.remotes.values()][0]; return r && { x: r.pos?.x, y: r.pos?.y, z: r.pos?.z } }))
await a.evaluate(({ x, z }) => { const g = window.__game; const p = g.player.position ?? g.localPose(); const ax = g.localPose().x, az = g.localPose().z; const yaw = Math.atan2(-(x - ax), -(z - az)); g.player.yaw = yaw; g.character.yaw = yaw }, bp)
await sleep(1500)
await a.screenshot({ path: `${OUT}/4b-a-sees-b.png` })
// A opens the room card, changes settings
await a.click('[data-testid=room-button]')
await sleep(500)
await a.screenshot({ path: `${OUT}/5-room-card-owner.png` })
await a.evaluate(() => window.__game.net.configure({ max_players: 8, private: true }))
await sleep(500)
log('A after configure', await net(a), 'B sees', await net(b))
log('public list now', await (await fetch('http://localhost:7350/v1/rooms')).json())
await b.click('[data-testid=room-button]')
await sleep(500)
await b.screenshot({ path: `${OUT}/6-room-card-guest.png` })
await b.keyboard.press('Escape')
// kick B
const bId = (await net(b)).me
await a.click(`[data-testid=kick-${bId}]`)
await sleep(1500)
log('B after kick', await net(b), 'A', await net(a))
await b.screenshot({ path: `${OUT}/7-b-kicked.png` })
// mobile landing: the floating button + modal
await a.evaluate(() => window.__game.net.configure({ private: false }))
const ctxC = await browser.createBrowserContext()
const c = await ctxC.newPage()
await c.emulate({ viewport: { width: 844, height: 390, isMobile: true, hasTouch: true, deviceScaleFactor: 2 }, userAgent: 'Mozilla/5.0 (Linux; Android 13; Pixel 7) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Mobile Safari/537.36' })
await c.goto(URL + '?tier=low', { waitUntil: 'domcontentloaded' })
await c.waitForFunction(() => window.__game, { timeout: 120_000, polling: 250 })
await sleep(1500)
await c.screenshot({ path: `${OUT}/8-mobile-landing.png` })
await c.tap('[data-testid=rooms-fab]')
await sleep(1200)
await c.screenshot({ path: `${OUT}/9-mobile-modal.png` })
await c.setViewport({ width: 390, height: 844, isMobile: true, hasTouch: true, deviceScaleFactor: 2 })
await c.keyboard.press('Escape')
await sleep(800)
await c.screenshot({ path: `${OUT}/10-mobile-portrait.png` })
await browser.close()
