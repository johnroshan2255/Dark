// EXPORT VEHICLES for the server's physics (dev-only: needs `npm run dev`): every catalogue car exactly as the game
// builds it — the model's measured dims and convex body hulls (assets/loadModels bakeVehicle), the catalogue's stock
// setup and its spec resolved against the model (drivetrain/spec resolveSpec) — to
// ../server/crates/vehicle/data/vehicles.json (compiled into the server). Rerun after changing a car, a model or a spec.
//   node scripts/export-vehicles.mjs        env: PORT (5173), CHROME
import puppeteer from 'puppeteer-core'
import fs from 'node:fs'

const OUT = '../server/crates/vehicle/data/vehicles.json'
const CHROME = process.env.CHROME || (process.platform === 'win32' ? 'C:/Program Files/Google/Chrome/Application/chrome.exe' : '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome')
const browser = await puppeteer.launch({ executablePath: CHROME, headless: 'new', protocolTimeout: 0, args: ['--use-angle=metal', '--mute-audio'] })
const page = await browser.newPage()
page.on('pageerror', (e) => console.log('[pageerror]', e.message))
await page.goto(`http://localhost:${process.env.PORT || 5173}/?map=island&tier=low&net=0&play=1`, { waitUntil: 'load' })
await page.waitForFunction(() => window.__game && window.__game.worldReadiness() >= 1, { timeout: 180_000, polling: 250 })
const cars = await page.evaluate(async () => {
  const g = window.__game
  // (Vite serves the game's own modules: the same catalogue and resolver the game runs)
  const { VEHICLES } = await import('/src/gameplay/vehicle/catalogue.ts')
  const { resolveSpec } = await import('/src/gameplay/vehicle/drivetrain/spec.ts')
  const out = []
  for (const def of VEHICLES) {
    await g.selectVehicle(def.id)
    for (let i = 0; i < 200 && g.car.modelId !== def.id; i++) await new Promise((r) => setTimeout(r, 50))
    const d = g.car.sim.dims
    const dims = {
      wheelPos: d.wheelPos,
      wheelRadius: d.wheelRadius,
      half: d.half,
      overhang: d.overhang ?? null,
      hulls: (d.hulls ?? []).map((h) => Array.from(h)),
      tyreHalfWidth: d.tyreHalfWidth ?? null,
    }
    const { paint: _paint, ...stock } = def.stock
    out.push({ id: def.id, dims, stock, resolved: resolveSpec(def.spec, { wheelPos: d.wheelPos, half: d.half }) })
  }
  return out
})
fs.mkdirSync('../server/crates/vehicle/data', { recursive: true })
fs.writeFileSync(OUT, JSON.stringify({ note: 'generated by game/scripts/export-vehicles.mjs — do not edit', cars }, null, 0))
for (const c of cars) console.log(`${c.id}: wheel r ${c.dims.wheelRadius.toFixed(3)}, ${c.dims.hulls.length} hulls (${c.dims.hulls.reduce((s, h) => s + h.length / 3, 0)} points), mass ${c.stock.mass}, ${c.resolved.gearbox.kind}`)
await browser.close()
